def print_summary(queue, enrichment_log, excel_file, csv_file, domain_file, missing_count, batch_dir, batch_count):
    counts = Counter(d["priority"] for d in queue)
    enriched = sum(d["traffic_status"] != "未补充" for d in queue)

    print("\n=== Arkswift Semrush Backlink Action Engine ===")
    print(f"数据库: {DB_FILE}")
    print(f"来源域名总数: {len(queue):,}")
    print("优先级分布:")
    for p in ["P0", "P1", "P2", "P3", "Drop"]:
        print(f"  {p}: {counts.get(p, 0):,}")
    print(f"已有 Semrush 域名级流量/AS 补充: {enriched:,}")
    print(f"仍待补充流量的可执行域名: {missing_count:,}")

    if enrichment_log:
        print("\ntraffic/ 导入日志:")
        for item in enrichment_log:
            print("  -", " | ".join(str(x) for x in item))

    print("\n输出:")
    print(f"  Excel: {excel_file}")
    print(f"  CSV:   {csv_file}")
    print(f"  待补流量域名: {domain_file}")
    print(f"  Semrush Bulk 批次: {batch_dir}  ({batch_count} 个批次，每批最多 200)")
    print("\n排序逻辑: P0 → P1 → P2 → P3 → Drop；每层内部按机器评分降序。")
    print("注意: P0-P3 是获取路径；机器评分是机会价值。两者不再混为一谈。")


def run():
    if not HAS_OPENPYXL:
        print("[错误] 请先安装 openpyxl: pip install openpyxl")
        return 1

    try:
        print("[1/4] 读取 Semrush backlink intelligence 数据库...")
        rows = load_backlinks()
        if not rows:
            print("[结束] 数据库中没有 backlink 行。请先运行 link-read.py。")
            return 0

        print("[2/4] 读取可选 Semrush Authority/Traffic 补充数据...")
        enrichment, enrichment_log = load_semrush_enrichment()

        print("[3/4] 生成 P0/P1/P2/P3/Drop 执行优先级与机器评分...")
        queue = build_action_queue(rows, enrichment)

        print("[4/4] 输出 Excel / CSV / Semrush 待补流量域名清单...")
        excel_file = generate_excel(queue, enrichment_log)
        csv_file = generate_csv(queue)
        domain_file, missing_count, batch_dir, batch_count = generate_enrichment_domain_list(queue)

        print_summary(queue, enrichment_log, excel_file, csv_file, domain_file, missing_count, batch_dir, batch_count)
        return 0

    except Exception as exc:
        print(f"\n[错误] {type(exc).__name__}: {exc}")
        return 1


if __name__ == "__main__":
    raise SystemExit(run())
