def alpha_component(alpha):
    # Retains the spirit of the old overlap score without letting overlap define acquisition path.
    if alpha >= 7:
        return 100
    if alpha == 6:
        return 92
    if alpha == 5:
        return 84
    if alpha == 4:
        return 72
    if alpha == 3:
        return 58
    if alpha == 2:
        return 40
    return 20


def traffic_component(traffic):
    """Semrush organic traffic score. None = missing/unknown, not zero."""
    if traffic is None:
        return None
    traffic = max(0.0, safe_float(traffic, 0))
    if traffic == 0:
        return 0
    if traffic < 50:
        return 55
    if traffic < 500:
        return 70
    if traffic < 5_000:
        return 82
    if traffic < 50_000:
        return 92
    return 100


def visits_component(visits):
    if visits is None:
        return None
    visits = max(0.0, safe_float(visits, 0))
    if visits == 0:
        return 0
    # Smooth log scaling. 1k ~= 60; 10k ~= 80; 100k+ approaches 100.
    return clamp(20 + 20 * math.log10(visits + 1), 0, 100)


def compute_machine_score(d):
    """
    Dynamic weighted score.

    Missing optional Semrush traffic metrics are removed from the denominator,
    so a domain is not punished simply because the user has not enriched it yet.
    """
    authority = d["domain_authority_score"]
    authority_signal = safe_float(authority, 0) if authority is not None else d["max_page_as"]

    components = [
        ("Authority", clamp(authority_signal), 0.30),
        ("Alpha", alpha_component(d["alpha"]), 0.20),
        ("Live", clamp(d["live_rate"] * 100), 0.12),
        ("Follow", clamp(d["live_follow_rate"] * 100), 0.10),
        ("Avg Page AS", clamp(d["live_avg_page_as"]), 0.08),
        ("High Page AS", clamp(d["high_page_as_rate"] * 100), 0.05),
    ]

    org_score = traffic_component(d["organic_traffic"])
    visit_score = visits_component(d["monthly_visits"])
    if org_score is not None:
        components.append(("Organic Traffic", org_score, 0.10))
    if visit_score is not None:
        components.append(("Monthly Visits", visit_score, 0.05))

    weighted_sum = sum(score * weight for _, score, weight in components)
    weight_sum = sum(weight for _, _, weight in components)
    base = weighted_sum / weight_sum if weight_sum else 0

    # Structural penalties; not enough to turn a legitimate domain into Drop.
    penalty = 0.0
    if d["sitewide_rate"] >= 0.50:
        penalty += 8
    elif d["sitewide_rate"] >= 0.20:
        penalty += 4

    if d["sponsored_rate"] >= 0.50:
        penalty += 6
    elif d["sponsored_rate"] >= 0.20:
        penalty += 3

    if d["ugc_rate"] >= 0.70:
        penalty += 4

    # History-only domains are still valid prospects, but less urgent.
    if d["live_backlinks"] == 0:
        penalty += 8

    score = round(clamp(base - penalty), 1)
    breakdown = "; ".join(f"{name}={score_:.0f}×{weight:.0%}" for name, score_, weight in components)
    if penalty:
        breakdown += f"; Penalty=-{penalty:.0f}"
    return score, breakdown


