def build_action_queue(rows, enrichment):
    grouped = group_by_ref_domain(rows)
    output = []

    for domain, domain_rows in grouped.items():
        d = summarize_domain(domain, domain_rows, enrichment)
        classification = classify_priority(domain, domain_rows)
        score, score_breakdown = compute_machine_score(d)

        if classification["priority"] == "Drop":
            # Keep audit visibility but force Drop to the bottom irrespective of score.
            effective_score = min(score, 25.0)
        else:
            effective_score = score

        total_links_text = (
            f"总计:{d['backlinks']} | "
            + ", ".join(f"{k}:{v}" for k, v in sorted(d["competitor_link_counts"].items()))
        )

        traffic_status = "已补充"
        if d["domain_authority_score"] is None and d["monthly_visits"] is None and d["organic_traffic"] is None:
            traffic_status = "未补充"
        elif d["organic_traffic"] is None:
            traffic_status = "部分补充"

        output.append({
            "priority": classification["priority"],
            "priority_label": PRIORITY_LABEL[classification["priority"]],
            "priority_rank": PRIORITY_RANK[classification["priority"]],
            "domain": domain,
            "machine_score": effective_score,
            "score_breakdown": score_breakdown,
            "classification_confidence": classification["confidence"],
            "machine_method": classification["method"],
            "action_suggested": classification["action"],
            "classification_evidence": classification["evidence"],
            "alpha": d["alpha"],
            "competitors": ", ".join(d["competitors"]),
            "total_links": total_links_text,
            "backlinks": d["backlinks"],
            "live_backlinks": d["live_backlinks"],
            "live_rate": d["live_rate"],
            "source_pages": d["source_pages"],
            "target_pages": d["target_pages"],
            "domain_authority_score": d["domain_authority_score"],
            "max_page_as": d["max_page_as"],
            "avg_page_as": d["avg_page_as"],
            "live_avg_page_as": d["live_avg_page_as"],
            "high_page_as_rate": d["high_page_as_rate"],
            "organic_traffic": d["organic_traffic"],
            "monthly_visits": d["monthly_visits"],
            "organic_keywords": d["organic_keywords"],
            "traffic_status": traffic_status,
            "traffic_source": ", ".join(d["enrichment_sources"]),
            "follow_rate": d["follow_rate"],
            "live_follow_rate": d["live_follow_rate"],
            "sitewide_rate": d["sitewide_rate"],
            "sponsored_rate": d["sponsored_rate"],
            "ugc_rate": d["ugc_rate"],
            "avg_external_links": d["avg_external_links"],
            "earliest_first_seen": d["earliest_first_seen"],
            "latest_last_seen": d["latest_last_seen"],
            "sample_links": "\n\n".join(d["samples"]),
        })

    # Priority decides workflow. Score decides order INSIDE priority.
    output.sort(
        key=lambda x: (
            x["priority_rank"],
            -x["machine_score"],
            -(x["domain_authority_score"] if x["domain_authority_score"] is not None else x["max_page_as"]),
            -(x["organic_traffic"] if x["organic_traffic"] is not None else -1),
            -x["alpha"],
            x["domain"],
        )
    )
    return output


