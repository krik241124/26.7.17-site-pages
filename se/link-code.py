def pick_header(headers, aliases):
    normalized = {normalize_header(h): h for h in headers}
    for alias in aliases:
        if normalize_header(alias) in normalized:
            return normalized[normalize_header(alias)]
    # fuzzy contains fallback, conservative
    for nh, original in normalized.items():
        for alias in aliases:
            a = normalize_header(alias)
            if a and (nh == a or nh.endswith(" " + a) or nh.startswith(a + " ")):
                return original
    return None


def read_csv_or_tsv(path):
    attempts = [
        ("utf-8-sig", "\t" if path.lower().endswith(".tsv") else ","),
        ("utf-16", "\t"),
        ("utf-8", "\t" if path.lower().endswith(".tsv") else ","),
        ("latin1", ","),
    ]
    last = None
    for encoding, delimiter in attempts:
        try:
            with open(path, "r", encoding=encoding, newline="") as f:
                reader = csv.DictReader(f, delimiter=delimiter)
                if not reader.fieldnames or len(reader.fieldnames) < 2:
                    continue
                return [dict(r) for r in reader], list(reader.fieldnames)
        except Exception as exc:
            last = exc
    raise ValueError(f"无法读取 {path}: {last}")


def read_xlsx_rows(path):
    if not HAS_OPENPYXL:
        raise RuntimeError("读取 xlsx enrichment 需要 openpyxl")
    wb = load_workbook(path, read_only=True, data_only=True)
    # Prefer the first non-empty sheet.
    for ws in wb.worksheets:
        rows = ws.iter_rows(values_only=True)
        try:
            first = next(rows)
        except StopIteration:
            continue
        headers = [str(x or "").strip() for x in first]
        if len([h for h in headers if h]) < 2:
            continue
        out = []
        for values in rows:
            record = {}
            for i, h in enumerate(headers):
                if not h:
                    continue
                record[h] = values[i] if i < len(values) else None
            out.append(record)
        wb.close()
        return out, headers
    wb.close()
    return [], []


def load_semrush_enrichment():
    """
    Return mapping:
      domain -> {
          authority_score: float|None,
          monthly_visits: float|None,
          organic_traffic: float|None,
          organic_keywords: float|None,
          source_files: set[str]
      }

    Multiple exports are merged using MAX for numeric metrics because a domain may
    appear in multiple Semrush files/country databases. We keep source filenames.
    """
    os.makedirs(TRAFFIC_DIR, exist_ok=True)
    files = sorted(
        glob.glob(os.path.join(TRAFFIC_DIR, "*.csv"))
        + glob.glob(os.path.join(TRAFFIC_DIR, "*.tsv"))
        + glob.glob(os.path.join(TRAFFIC_DIR, "*.xlsx"))
    )

    result = {}
    import_log = []

    for path in files:
        try:
            if path.lower().endswith(".xlsx"):
                rows, headers = read_xlsx_rows(path)
            else:
                rows, headers = read_csv_or_tsv(path)
        except Exception as exc:
            import_log.append((os.path.basename(path), "ERROR", str(exc)))
            continue

        if not rows or not headers:
            import_log.append((os.path.basename(path), "EMPTY", "无数据"))
            continue

        h_domain = pick_header(headers, DOMAIN_ALIASES)
        h_as = pick_header(headers, AUTHORITY_ALIASES)
        h_visits = pick_header(headers, MONTHLY_VISITS_ALIASES)
        h_org = pick_header(headers, ORGANIC_TRAFFIC_ALIASES)
        h_kw = pick_header(headers, ORGANIC_KEYWORDS_ALIASES)

        if not h_domain:
            import_log.append((os.path.basename(path), "SKIP", "未识别 Domain/URL 列"))
            continue

        imported = 0
        for row in rows:
            domain = clean_domain(row.get(h_domain))
            if not domain:
                continue

            rec = result.setdefault(domain, {
                "authority_score": None,
                "monthly_visits": None,
                "organic_traffic": None,
                "organic_keywords": None,
                "source_files": set(),
            })

            for key, header in [
                ("authority_score", h_as),
                ("monthly_visits", h_visits),
                ("organic_traffic", h_org),
                ("organic_keywords", h_kw),
            ]:
                if not header:
                    continue
                raw = row.get(header)
                if raw is None or str(raw).strip() == "":
                    continue
                value = safe_float(raw, None)
                if value is None:
                    continue
                if rec[key] is None:
                    rec[key] = value
                else:
                    rec[key] = max(rec[key], value)

            rec["source_files"].add(os.path.basename(path))
            imported += 1

        import_log.append((os.path.basename(path), "OK", f"读取 {imported} 行"))

    for rec in result.values():
        rec["source_files"] = sorted(rec["source_files"])

    return result, import_log


