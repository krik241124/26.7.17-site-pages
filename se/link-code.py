def load_backlinks():
    if not os.path.exists(DB_FILE):
        raise FileNotFoundError(
            f"未找到 {DB_FILE}\n"
            "请先运行 link-read.py，生成 semrush_backlink_intelligence.db。"
        )

    conn = sqlite3.connect(DB_FILE)
    conn.row_factory = sqlite3.Row
    cur = conn.cursor()

    # Validate expected schema; do not mutate the database.
    cur.execute("PRAGMA table_info(backlinks)")
    cols = {r[1] for r in cur.fetchall()}
    required = {
        "competitor_domain", "ref_domain", "source_title", "source_url", "target_url",
        "anchor", "page_ascore", "external_links", "is_nofollow", "is_sponsored",
        "is_ugc", "is_sitewide", "is_lost", "first_seen", "last_seen"
    }
    missing = sorted(required - cols)
    if missing:
        conn.close()
        raise RuntimeError(
            "数据库不是当前 Semrush link-read.py 的 schema，缺少列：" + ", ".join(missing)
        )

    cur.execute("SELECT * FROM backlinks")
    rows = [dict(r) for r in cur.fetchall()]
    conn.close()
    return rows


def group_by_ref_domain(rows):
    grouped = defaultdict(list)
    for r in rows:
        domain = str(r.get("ref_domain") or "").strip().lower()
        if domain:
            grouped[domain].append(r)
    return grouped


