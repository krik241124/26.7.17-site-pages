def summarize_domain(domain, rows, enrichment):
    live = [r for r in rows if not safe_int(r.get("is_lost"), 0)]
    competitors = sorted({str(r.get("competitor_domain") or "") for r in rows if r.get("competitor_domain")})
    source_pages = {str(r.get("source_url") or "") for r in rows if r.get("source_url")}
    target_pages = {str(r.get("target_url") or "") for r in rows if r.get("target_url")}

    page_as = [safe_float(r.get("page_ascore"), 0) for r in rows]
    live_page_as = [safe_float(r.get("page_ascore"), 0) for r in live]
